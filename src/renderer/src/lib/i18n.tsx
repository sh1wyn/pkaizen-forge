export type StrKey = keyof (typeof STR)['en']

interface I18nCtx {
  lang: Lang
  setLang: (l: Lang) => void
  t: (key: StrKey, ...args: (string | number)[]) => string
}

const Ctx = createContext<I18nCtx>({ lang: 'en', setLang: () => {}, t: (k) => k })

export function useI18n(): I18nCtx {
  return useContext(Ctx)
}

export function I18nProvider({ children }: { children: ReactNode }): React.JSX.Element {
  const [lang, setLangState] = useState<Lang>(getSavedLang())

  const setLang = useCallback((l: Lang) => {
    localStorage.setItem(LS_KEY, l)
    setLangState(l)
    window.api.setLang(l)
    invalidate() // les textes générés côté main doivent être rechargés dans la nouvelle langue
  }, [])

  const t = useCallback(
    (key: StrKey, ...args: (string | number)[]): string => {
      const dict = (STR as Record<string, Record<string, string>>)[lang] ?? STR.en
      let s: string = dict[key] ?? STR.en[key] ?? key
      args.forEach((a, i) => {
        s = s.replace(`{${i}}`, String(a))
      })
      return s
    },
    [lang]
  )

  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>
}
